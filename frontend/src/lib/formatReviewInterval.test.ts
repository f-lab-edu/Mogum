import { expect, test } from 'vitest'
import { formatReviewInterval } from './formatReviewInterval'

test.each([
  [0, '1분'], [29, '1분'], [60, '1분'], [89, '1분'], [90, '2분'],
  [600, '10분'], [3569, '59분'], [3570, '1시간'],
  [3599, '1시간'], [3600, '1시간'], [5399, '1시간'], [5400, '2시간'],
  [84599, '23시간'], [84600, '1일'],
  [86399, '1일'], [86400, '1일'], [129599, '1일'], [129600, '2일'],
  [3 * 86400, '3일'], [2548799, '29일'], [2548800, '1달'],
  [30 * 86400 - 1, '1달'], [30 * 86400, '1달'],
  [45 * 86400 - 1, '1달'], [45 * 86400, '2달'],
  [29807999, '11달'], [29808000, '1년'],
  [365 * 86400 - 1, '1년'], [365 * 86400, '1년'],
  [547.5 * 86400 - 1, '1년'], [547.5 * 86400, '2년'],
])('%s초는 %s로 표시한다', (seconds, expected) => {
  expect(formatReviewInterval(seconds as number)).toBe(expected)
})
